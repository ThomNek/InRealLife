-- updated_at của hồ sơ là dữ liệu hệ thống, không lấy từ đồng hồ thiết bị.

create or replace function public.set_profile_updated_at()
returns trigger
language plpgsql
set search_path = public
as $$
begin
  new.updated_at := clock_timestamp();
  return new;
end;
$$;

drop trigger if exists set_profile_updated_at_trigger on public.profiles;
create trigger set_profile_updated_at_trigger
before update on public.profiles
for each row execute function public.set_profile_updated_at();

revoke insert (updated_at) on table public.profiles from authenticated;
revoke update (updated_at) on table public.profiles from authenticated;

comment on function public.set_profile_updated_at() is
  'QuestReal migration 028: profiles.updated_at is generated by the server.';
comment on column public.profiles.updated_at is
  'Thời gian server; client không được tự đặt.';

notify pgrst, 'reload schema';
